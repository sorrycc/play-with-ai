export type Lang = 'zh' | 'en';
const DICTS: Record<Lang, Record<TextKey, string>> = { zh, en };
const STORAGE_KEY = 'play-with-ai:lang';
const DEFAULT_LANG: Lang = 'zh';

function readLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === 'en' || saved === 'zh' ? saved : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG; // no storage (private window, tests): the default
  }
}

let lang: Lang = readLang();
const listeners = new Set<() => void>();

function applyToDocument(): void {
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}
applyToDocument();

/** Text for `key` in the current language, with `{name}` placeholders filled from `params`. */
export function t(key: TextKey, params?: Record<string, string | number>): string {
  const text = DICTS[lang][key];
  return params ? text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole)) : text;
}

export const i18n = {
  get lang(): Lang {
    return lang;
  },
  setLang(next: Lang): void {
    lang = next;
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* the choice lasts for this page only */
    }
    applyToDocument();
    listeners.forEach((l) => l());
  },
  /** For useSyncExternalStore. */
  subscribe(listener: () => void): () => void {
    listeners.add(listener);
    return () => listeners.delete(listener);
  },
};
